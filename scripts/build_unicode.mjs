// Generates src/plagx_preflight/_unicode.py: Unicode character classes taken from
// the JavaScript regex engine (\p{L}, \p{M}, \p{Lu}, \p{Ll}), so the Python port
// matches the JavaScript reference exactly. Python's re module has no \p{...}.
// Usage: node scripts/build_unicode.mjs
import { writeFileSync } from 'node:fs';

function ranges(re) {
  const out = [];
  let start = -1;
  for (let cp = 0; cp <= 0x110000; cp += 1) {
    const hit = cp < 0x110000 && !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (hit && start < 0) start = cp;
    if (!hit && start >= 0) {
      out.push([start, cp - 1]);
      start = -1;
    }
  }
  return out;
}

const esc = (cp) => (cp <= 0xffff ? `\\u${cp.toString(16).padStart(4, '0')}` : `\\U${cp.toString(16).padStart(8, '0')}`);
const cls = (list) => list.map(([a, b]) => (a === b ? esc(a) : `${esc(a)}-${esc(b)}`)).join('');
const wrap = (s) => s.match(/.{1,96}(?=\\|$)/g).map((l) => `    "${l}"`).join('\n');

const sets = { L: /\p{L}/u, M: /\p{M}/u, LU: /\p{Lu}/u, LL: /\p{Ll}/u };
let py = `"""Unicode character classes for regular expressions (contents of [...]).

Generated by scripts/build_unicode.mjs from the JavaScript regex engine (Node ${process.versions.node},
Unicode ${process.versions.unicode}) so results match the JavaScript reference. Do not edit.
"""\n`;
for (const [name, re] of Object.entries(sets)) py += `\n${name} = (\n${wrap(cls(ranges(re)))}\n)\n`;
writeFileSync(new URL('../src/plagx_preflight/_unicode.py', import.meta.url), py);
console.log('Wrote src/plagx_preflight/_unicode.py');
